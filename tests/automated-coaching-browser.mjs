page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) errors.push(response.status() + ' ' + response.url()); });
const dialog = page.locator('#coaching-preview-dialog');
const action = name => dialog.locator('[data-cp-action="' + name + '"]');
const state = () => page.evaluate(() => CoachingPreview.getState());
const latest = async (program = 'speeding') => (await state()).assignments.filter(a => a.programId === program).at(-1);
const advance = async days => { await dialog.locator('#cp-days').fill(String(days)); await dialog.locator('#cp-advance-form button[type="submit"]').click(); };
const answer = async (wrongFirst = false) => {
  const snapshot = await state();
  const a = snapshot.assignments.findLast(item => item.status === 'delivered');
  for (const [i, q] of a.courseSnapshot.questions.entries()) {
    if (a.correctQuestionIds.includes(q.id)) continue;
    const index = wrongFirst && i === 0 ? (q.correctIndex + 1) % q.options.length : q.correctIndex;
    await dialog.locator('input[name="quiz-' + q.id + '"][value="' + index + '"]').check();
  }
  await dialog.locator('#cp-submit-quiz').click();
};

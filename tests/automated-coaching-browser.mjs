  assert.equal(await dialog.locator('.cp-question').count(), 1, 'Only the missed question should need a retry');
  assert.match(await dialog.textContent(), /Try again|explanation/i);
  await answer();
  assert.equal((await latest()).status, 'completed');
  assert.equal((await state()).journeys.find(j => j.programId === 'speeding').stage, 'monitoring');
  await action('next-assessment').click();
  assert.equal((await latest()).cycle, 2);
  await action('deliver').click();
